import { gradeOf } from '../../shared/grade';
import type { Lang, Question, Report, Score, Stage } from '../../shared/schema';

type Item = { questionId: string; stage: Stage; score: Score };

const top = (xs: string[], n: number) => {
  const c = new Map<string, number>();
  xs.forEach((x) => c.set(x, (c.get(x) ?? 0) + 1));
  return [...c.entries()].sort((a, b) => b[1] - a[1]).slice(0, n).map(([x]) => x);
};

export function localReport(input: { items: Item[]; questions: Question[]; interviewers: { id: string; displayName: string; title: string }[]; lang: Lang; company: string; role: string }): Report {
  const ko = input.lang === 'ko';
  const n = Math.max(1, input.items.length);
  const avg = Math.round(input.items.reduce((s, i) => s + i.score.score, 0) / n);
  const verdict = avg >= 75 ? 'pass' : avg >= 60 ? 'hold' : 'fail';
  const weakest = [...input.items].sort((a, b) => a.score.score - b.score.score);
  const seeds = weakest.flatMap((i) => input.questions.find((q) => q.id === i.questionId)?.followUpSeeds ?? []).filter(Boolean);
  const vText = ko ? { pass: '합격', hold: '보류', fail: '불합격' }[verdict] : verdict;
  return {
    local: true,
    publicSummary: { company: input.company, role: input.role, grade: gradeOf(avg), score: avg, verdict, oneLiner: ko ? `평균 ${avg}점, ${vText} 성향` : `Average ${avg}, leaning ${verdict}` },
    privateDetail: {
      verdictReason: ko
        ? `답변 ${input.items.length}개의 평균은 ${avg}점입니다. 가장 낮은 문항은 ${weakest[0]?.score.score ?? 0}점이었습니다. (간이 리포트: AI 연결이 원활하지 않아 규칙 기반으로 작성)`
        : `Average of ${input.items.length} answers is ${avg}. Lowest was ${weakest[0]?.score.score ?? 0}. (Basic report generated by rules because AI was unavailable.)`,
      interviewerComments: input.interviewers.map((iv) => ({ interviewerId: iv.id, comment: ko ? (avg >= 75 ? '전반적으로 준비가 잘 되어 있었습니다.' : '근거와 수치를 더 보강하면 좋겠습니다.') : avg >= 75 ? 'Well prepared overall.' : 'Back your claims with more evidence and numbers.' })),
      top3Strengths: top(input.items.flatMap((i) => i.score.strengths), 3),
      top3Fixes: top(input.items.flatMap((i) => i.score.improvements), 3),
      nextQuestions: [...new Set(seeds)].slice(0, 3),
    },
  };
}
